-- 控制面初始模型。事件、告警和实体风险仍保留在 Elasticsearch。

CREATE TABLE roles (
    name             VARCHAR(32) PRIMARY KEY,
    description      VARCHAR(255) NOT NULL,
    permissions_json TEXT NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

