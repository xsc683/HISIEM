-- SOAR V3：租户隔离、版本发布治理、父子流程和分布式 Connector 保护状态。
CREATE TABLE tenants (
    id          VARCHAR(64) PRIMARY KEY,
    name        VARCHAR(128) NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'active',
    created_by  VARCHAR(128) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tenants_status_ck CHECK (status IN ('active', 'disabled'))
);

INSERT INTO tenants(id, name, created_by) VALUES ('default', '默认租户', 'migration');

CREATE TABLE tenant_memberships (
    tenant_id   VARCHAR(64) NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    username    VARCHAR(128) NOT NULL REFERENCES users(username) ON DELETE CASCADE,
    tenant_role VARCHAR(32) NOT NULL DEFAULT 'member',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tenant_id, username),
    CONSTRAINT tenant_membership_role_ck CHECK (tenant_role IN ('owner', 'member', 'viewer'))
);

